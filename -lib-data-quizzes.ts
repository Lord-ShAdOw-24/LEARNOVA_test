const DIFF_RANK: Record<Difficulty, number> = { low: 0, medium: 1, high: 2 };

export function pickQuestions(level: "O-Level" | "A-Level", subject: string, difficulty: Difficulty, n = 10): Question[] {
  const min = DIFF_RANK[difficulty];
  let pool = QUESTIONS.filter((q) => q.level === level && q.subject === subject && DIFF_RANK[q.difficulty] >= min);
  if (pool.length < n) {
    pool = QUESTIONS.filter((q) => q.level === level && q.subject === subject);
  }
  if (pool.length < n) {
    pool = QUESTIONS.filter((q) => q.subject === subject);
  }
  if (pool.length < n) pool = QUESTIONS.slice();
  const copy = pool.slice();
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy.slice(0, n);
}

